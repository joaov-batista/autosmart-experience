"""Split / trim ElevenLabs narration takes into per-line clips and write the
timing meta used by src/timeline.js.

  python3 tools/narration.py combined <take.mp3> N02,N03,N05,...   (split at the longest pauses)
  python3 tools/narration.py single <take.mp3> N01                 (trim one line)
  python3 tools/narration.py meta                                  (rebuild durations + JS meta)
"""
import json, os, re, subprocess, sys
import numpy as np
from scipy.io import wavfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIPS = os.path.join(ROOT, 'audio', 'narration', 'clips')
SR = 48000


def load(path):
    tmp = os.path.join(ROOT, 'build', 'nar_tmp.wav')
    os.makedirs(os.path.dirname(tmp), exist_ok=True)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-c:a', 'pcm_f32le', tmp], check=True)
    _, x = wavfile.read(tmp)
    return x.astype(np.float64)


def frames_db(x, win=0.02):
    n = int(win * SR)
    k = len(x) // n
    r = np.sqrt(np.mean(x[:k * n].reshape(k, n) ** 2, axis=1))
    return 20 * np.log10(r + 1e-9), n


def silences(x, thr=-45, min_len=0.25):
    d, n = frames_db(x)
    quiet = d < thr
    out = []
    i = 0
    while i < len(quiet):
        if quiet[i]:
            j = i
            while j < len(quiet) and quiet[j]:
                j += 1
            if (j - i) * n / SR >= min_len:
                out.append((i * n / SR, j * n / SR))
            i = j
        else:
            i += 1
    return out


def trim(x, thr=-48, pad=0.04):
    d, n = frames_db(x)
    loud = np.where(d > thr)[0]
    if not len(loud):
        return x
    a = max(0, loud[0] * n - int(pad * SR))
    b = min(len(x), (loud[-1] + 1) * n + int(pad * SR))
    y = x[a:b].copy()
    f = int(0.008 * SR)
    y[:f] *= np.linspace(0, 1, f)
    y[-f:] *= np.linspace(1, 0, f)
    return y


def save(id_, y):
    os.makedirs(CLIPS, exist_ok=True)
    wavfile.write(os.path.join(CLIPS, id_ + '.wav'), SR, y.astype(np.float32))
    print(f'  {id_}: {len(y) / SR:.2f}s')


def combined(path, ids):
    x = load(path)
    sil = [s for s in silences(x) if s[0] > 0.2 and s[1] < len(x) / SR - 0.2]
    need = len(ids) - 1
    longest = sorted(sorted(sil, key=lambda s: s[1] - s[0], reverse=True)[:need])
    if len(longest) < need:
        raise SystemExit(f'found only {len(longest)} pauses, need {need}')
    lens = [round(b - a, 2) for a, b in longest]
    rest = sorted([round(b - a, 2) for a, b in sil if (a, b) not in longest], reverse=True)[:3]
    print(f'split pauses (s): {lens}; next longest inside lines: {rest}')
    cuts = [0] + [(a + b) / 2 for a, b in longest] + [len(x) / SR]
    # sanity: clip duration should follow the text length
    tl = json.load(open(os.path.join(ROOT, 'build', 'timeline.json')))
    text = {l['id']: l['text'] for l in tl['lines']}
    for k, id_ in enumerate(ids):
        y = trim(x[int(cuts[k] * SR):int(cuts[k + 1] * SR)])
        rate = len(text[id_]) / (len(y) / SR)
        flag = '' if 11 < rate < 22 else '   <-- check'
        print(f'  {id_} chars/s {rate:.1f}{flag}')
        save(id_, y)


def single(path, id_):
    save(id_, trim(load(path)))


def meta():
    out = {}
    for f in sorted(os.listdir(CLIPS)):
        if f.endswith('.wav'):
            sr, y = wavfile.read(os.path.join(CLIPS, f))
            out[f[:-4]] = {'dur': round(len(y) / sr, 3), 'file': 'audio/narration/clips/' + f}
    json.dump(out, open(os.path.join(ROOT, 'audio', 'narration', 'durations.json'), 'w'), indent=1)
    js = '/* generated by tools/narration.py meta — real narration durations */\nwindow.DG = window.DG || {};\nDG.NARR_META = ' + json.dumps(out, indent=1) + ';\n'
    os.makedirs(os.path.join(ROOT, 'src', 'generated'), exist_ok=True)
    open(os.path.join(ROOT, 'src', 'generated', 'narration_meta.js'), 'w').write(js)
    print('meta:', {k: v['dur'] for k, v in out.items()})


if __name__ == '__main__':
    cmd = sys.argv[1]
    if cmd == 'combined':
        combined(sys.argv[2], sys.argv[3].split(','))
    elif cmd == 'single':
        single(sys.argv[2], sys.argv[3])
    meta()
