"""Lip-sync data for the mascot: per-frame mouth openness (0..1) for every
narration clip, from a speech-band envelope → src/generated/mouth.js"""
import json, os
import numpy as np
from scipy import signal
from scipy.io import wavfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIPS = os.path.join(ROOT, 'audio', 'narration', 'clips')
FPS = 24
out = {}
for f in sorted(os.listdir(CLIPS)):
    if not f.endswith('.wav'):
        continue
    sr, x = wavfile.read(os.path.join(CLIPS, f))
    x = x.astype(np.float64)
    sos = signal.butter(4, [250, 3200], btype='band', fs=sr, output='sos')
    y = signal.sosfilt(sos, x)
    hop = sr // FPS
    n = len(y) // hop + 1
    e = np.array([np.sqrt(np.mean(y[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    d = 20 * np.log10(e + 1e-9)
    ref = np.percentile(d[d > -80], 90) if np.any(d > -80) else -20
    o = np.clip((d - (ref - 24)) / 22, 0, 1)
    # light smoothing + a little anticipation (mouth opens slightly before the sound)
    o = np.convolve(o, [0.2, 0.5, 0.3], mode='same')
    o = np.concatenate([o[1:], [0]])
    out[f[:-4]] = [round(float(v), 2) for v in o]
js = '/* generated by tools/mouth.py — mascot lip-sync (24 fps) */\nwindow.DG = window.DG || {};\nDG.MOUTH = ' + json.dumps(out) + ';\n'
open(os.path.join(ROOT, 'src', 'generated', 'mouth.js'), 'w').write(js)
print({k: len(v) for k, v in out.items()})
